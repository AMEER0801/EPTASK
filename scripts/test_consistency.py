"""Consistency check: live service output vs the notebook's recorded demo_data.json.

The demo bundle was generated by make_traces.py from the notebook run
20261008-124455-ba2667. The same simulation code runs live here, so for the
same inputs the outputs must match to the recorded rounding.
"""
import json
import sys

sys.path.insert(0, "/home/z/my-project/mini-services/eptask-api")
from app.corridor_svc import run_corridor  # noqa: E402
from app.state import STATE  # noqa: E402

STATE.load()
DEMO = json.load(open("/home/z/my-project/workspace/extracted/demo_raw/demo/demo_data.json"))

fails = []
for hz in ("earthquake", "landslide", "flood"):
    for mode in ("NONE", "V2V", "RSU", "V2V+RSU"):
        key = f"{hz}|{mode}"
        ref = DEMO["corridor"][key]
        out = run_corridor(dict(hazard=hz, info_mode=mode, convoy=True, trace=True))
        # 1) ambulance track equality (recorded rows are exactly what make_traces stored)
        if out["amb"] != ref["amb"]:
            n = min(len(out["amb"]), len(ref["amb"]))
            diff = next((i for i in range(n) if out["amb"][i] != ref["amb"][i]), None)
            fails.append(f"{key}: amb differs (len {len(out['amb'])} vs {len(ref['amb'])}, first diff @ {diff})")
            continue
        # 2) vehicle tracks equality
        if out["veh"] != ref["veh"]:
            fails.append(f"{key}: veh tracks differ (len {len(out['veh'])} vs {len(ref['veh'])})")
            continue
        # 3) summary equality (floats)
        s1, s2 = out["summary"], ref["summary"]
        bad = [k for k in ("arrival_min", "oracle_min", "extra_min", "informed_min") 
               if abs((s1.get(k) or 0) - (s2.get(k) or 0)) > 1e-9]
        bad += [k for k in ("missed_junction", "saw_block", "unreachable") if bool(s1[k]) != bool(s2[k])]
        if bad:
            fails.append(f"{key}: summary differs at {bad}: {({k: s1[k] for k in bad})} vs {({k: s2[k] for k in bad})}")
            continue
        print(f"OK {key:<22} amb rows={len(out['amb']):5d}  frames={out['n_frames']:4d}  "
              f"extra_min={out['summary']['extra_min']:.3f}")

# cell trace consistency (same params as make_traces.cell_trace defaults)
from app.cell_svc import run_cell  # noqa: E402

cell = run_cell(dict(policy="B", version=30, V=30, seed=21, ticks=520,
                     event=dict(at=60, k=3, dur=360), floor=True, explain=True))
ref_cell = DEMO["cell"]
my_ticks, ref_ticks = cell["ticks"], ref_cell["ticks"]
if len(my_ticks) != len(ref_ticks):
    fails.append(f"cell: tick count {len(my_ticks)} vs {len(ref_ticks)}")
else:
    for i, (a, b) in enumerate(zip(my_ticks, ref_ticks)):
        for f in ("t", "i", "n", "role", "prot", "tier", "edge_ok", "a", "real", "lvl", "s", "sev", "T", "D"):
            if a.get(f) != b.get(f):
                fails.append(f"cell tick {i}: field {f}: {a.get(f)} vs {b.get(f)}")
                break
        else:
            if a.get("Tt") is not None and b.get("Tt") is not None and abs(a["Tt"] - b["Tt"]) > 5e-4:
                fails.append(f"cell tick {i}: Tt {a['Tt']} vs {b['Tt']}")
                break
            continue
        break

if not fails:
    print("OK cell: 520 ticks identical to the recorded demo cell trace")
print()
if fails:
    print("CONSISTENCY FAILURES:")
    [print(" -", f) for f in fails]
    sys.exit(1)
print("ALL CONSISTENCY CHECKS PASSED (12 corridor traces + cell trace vs notebook recording)")
